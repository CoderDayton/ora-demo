// Packs dist/ into src/server/assets.gen.ts so the compiled server needs no files beside it.
// Usage: node scripts/embed.ts
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dist = join(root, 'dist');
const TEXT = new Set(['.html', '.js', '.css', '.json', '.svg', '.txt']);

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap(n => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const entries: string[] = [];
for (const file of walk(dist).sort()) {
  if (!TEXT.has(extname(file))) throw new Error(`embed: ${relative(dist, file)} is not a text asset; extend scripts/embed.ts first`);
  entries.push(`  ${JSON.stringify(relative(dist, file))}: ${JSON.stringify(readFileSync(file, 'utf8'))},`);
}
if (!entries.length) throw new Error('embed: dist/ is empty, run npm run build:web first');

writeFileSync(
  join(root, 'src/server/assets.gen.ts'),
  `// Generated by scripts/embed.ts. Do not edit.\nexport const ASSETS: Record<string, string> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`embedded ${entries.length} files`);
